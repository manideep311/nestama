// Sample products for development and demos. Every product is flagged isSample.
// Prices are in RUPEES here and converted to paise by the seed script.

export type PetTypeSeed = "DOG" | "CAT" | "BOTH";

export interface VariantSeed {
  sku: string;
  label: string;
  options: Record<string, string>;
  price: number;
  mrp?: number;
  stock: number;
}

export interface ProductSeed {
  slug: string;
  name: string;
  petType: PetTypeSeed;
  category: string;
  brand: string;
  images: { id: string; alt: string }[];
  short: string;
  description: string;
  specs: [string, string][];
  tags: string[];
  variants: VariantSeed[];
  rating: number;
  reviews: number;
  sold: number;
  featured?: boolean;
  /** Days before seeding that the product was published (drives New Arrivals). */
  daysAgo: number;
}

/** Build size variants that share pricing steps. */
function sizes(
  prefix: string,
  list: [label: string, price: number, mrp: number | undefined, stock: number][],
  key = "Size",
): VariantSeed[] {
  return list.map(([label, price, mrp, stock], i) => ({
    sku: `${prefix}-${String(i + 1).padStart(2, "0")}`,
    label,
    options: { [key]: label },
    price,
    mrp,
    stock,
  }));
}

const one = (sku: string, price: number, mrp: number | undefined, stock: number, label = "Standard"): VariantSeed[] => [
  { sku, label, options: {}, price, mrp, stock },
];

